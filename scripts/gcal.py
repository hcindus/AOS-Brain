#!/usr/bin/env python3
"""
Google Calendar helper for PSD appointments.

Target account: performancesupplydepotsales@gmail.com (primary calendar).

Requires an OAuth token (calendar scope) at aocros/secrets/google_calendar_token.json
— generated by `google_calendar_auth.py`.

Usage:
  import calendar as cal
  cal.book_appointment("Service call — Star Grocery", "2026-11-20T14:00:00", "2026-11-20T15:00:00",
                       description="...", attendee_email="nick@stargrocery.com")
  cal.list_events(time_min=..., time_max=...)
"""
import os
import json

BASE = "/root/.openclaw/workspace"
CLIENT = f"{BASE}/aocros/secrets/google_oauth_client.json"
TOKEN = f"{BASE}/aocros/secrets/google_calendar_token.json"
SCOPES = ["https://www.googleapis.com/auth/calendar"]

TZ = "America/Los_Angeles"


def _creds():
    from google.oauth2.credentials import Credentials
    c = json.load(open(CLIENT))["installed"]
    if not os.path.exists(TOKEN):
        raise RuntimeError("No calendar token — run google_calendar_auth.py first.")
    t = json.load(open(TOKEN))
    scope = t.get("scope", " ".join(SCOPES))
    creds = Credentials(
        token=t.get("access_token"),
        refresh_token=t.get("refresh_token"),
        token_uri=c["token_uri"],
        client_id=c["client_id"],
        client_secret=c["client_secret"],
        scopes=scope.split(" ") if isinstance(scope, str) else SCOPES,
    )
    if creds.expired and creds.refresh_token:
        from google.auth.transport.requests import Request
        creds.refresh(Request())
        t["access_token"] = creds.token
        json.dump(t, open(TOKEN, "w"))
    return creds


def _service():
    from googleapiclient.discovery import build
    return build("calendar", "v3", credentials=_creds(), cache_discovery=False)


def book_appointment(summary, start_iso, end_iso, description="", location="", attendee_email=None, calendar_id="primary"):
    svc = _service()
    event = {
        "summary": summary,
        "description": description,
        "start": {"dateTime": start_iso, "timeZone": TZ},
        "end": {"dateTime": end_iso, "timeZone": TZ},
    }
    if location:
        event["location"] = location
    if attendee_email:
        event["attendees"] = [{"email": attendee_email}]
    return svc.events().insert(calendarId=calendar_id, body=event, sendUpdates="all").execute()


def list_events(time_min=None, time_max=None, max_results=20, calendar_id="primary"):
    svc = _service()
    kwargs = {"calendarId": calendar_id, "maxResults": max_results, "singleEvents": True, "orderBy": "startTime"}
    if time_min:
        kwargs["timeMin"] = time_min
    if time_max:
        kwargs["timeMax"] = time_max
    return svc.events().list(**kwargs).execute().get("items", [])


if __name__ == "__main__":
    import sys
